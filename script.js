const selectoresSemanas = document.querySelectorAll('.week-selector');
const galeriasInfografias = document.querySelectorAll('.infografia-grid');
const visorImagen = document.querySelector('.image-dialog');
const tituloImagen = document.querySelector('#image-dialog-title');
const imagenAmpliada = document.querySelector('.image-dialog-content');
const enlaceDescargarImagen = document.querySelector('.image-dialog-download');
const botonAnterior = document.querySelector('.image-dialog-previous');
const botonSiguiente = document.querySelector('.image-dialog-next');
let imagenesVisor = [];
let indiceImagenActual = 0;

function obtenerNombre(ruta) {
	const nombreArchivo = (typeof ruta === 'string' ? ruta : ruta.src).split('/').pop();
	const nombreLimpio = nombreArchivo
		.replace(/\.[^.]+$/, '')
		.replace(/^s\d+[_\s-]*/i, '')
		.replace(/^infograf[ií]a[_\s-]*\d+[_\s-]*/i, '')
		.replace(/^\d+(?:[._-]\d+)*[._\s-]*/, '')
		.replace(/([a-záéíóúñ])([A-ZÁÉÍÓÚÑ])/g, '$1 $2')
		.replace(/[-_]+/g, ' ')
		.replace(/\s+/g, ' ')
		.trim()
		.toLocaleLowerCase('es');
	return nombreLimpio ? nombreLimpio[0].toLocaleUpperCase('es') + nombreLimpio.slice(1) : 'Infografía';
}

function obtenerMiniatura(ruta) {
	return ruta.replace(/^infografias\//, 'infografias/miniaturas/').replace(/\.[^.]+$/, '.webp');
}

function abrirImagen(indice) {
	indiceImagenActual = (indice + imagenesVisor.length) % imagenesVisor.length;
	const imagen = imagenesVisor[indiceImagenActual];
	tituloImagen.textContent = imagen.titulo;
	imagenAmpliada.src = imagen.src;
	imagenAmpliada.alt = imagen.titulo;
	imagenAmpliada.width = imagen.width;
	imagenAmpliada.height = imagen.height;
	enlaceDescargarImagen.href = imagen.src;
	enlaceDescargarImagen.download = imagen.src.split('/').pop();
	botonAnterior.disabled = imagenesVisor.length < 2;
	botonSiguiente.disabled = imagenesVisor.length < 2;
}

imagenAmpliada.addEventListener('load', () => {
	imagenAmpliada.width = imagenAmpliada.naturalWidth;
	imagenAmpliada.height = imagenAmpliada.naturalHeight;
});

function mostrarSemana(semana, galeriaInfografias) {
	galeriaInfografias.replaceChildren();
	galeriaInfografias.hidden = false;

	(infografiasPorSemana[semana] || []).forEach((actividad) => {
		const seccionActividad = document.createElement('section');
		const encabezado = document.createElement('div');
		const tituloActividad = document.createElement('h4');
		const galeriaActividad = document.createElement('div');

		seccionActividad.className = 'actividad-card';
		encabezado.className = 'actividad-header';
		tituloActividad.textContent = actividad.titulo;
		galeriaActividad.className = 'actividad-galeria';

		encabezado.append(tituloActividad);
		if (actividad.zip) {
			const enlaceDescarga = document.createElement('a');
			enlaceDescarga.className = 'actividad-download';
			enlaceDescarga.href = actividad.zip;
			enlaceDescarga.download = '';
			enlaceDescarga.textContent = `Descargar ZIP ${actividad.titulo}`;
			encabezado.append(enlaceDescarga);
		}

		actividad.imagenes.forEach((imagenData) => {
			const ruta = typeof imagenData === 'string' ? imagenData : imagenData.src;
			const nombre = (typeof imagenData === 'object' && imagenData.titulo) || obtenerNombre(imagenData);
			const tarjeta = document.createElement('button');
			const miniatura = document.createElement('img');
			const titulo = document.createElement('span');

			tarjeta.className = 'infografia-card';
			tarjeta.type = 'button';
			tarjeta.setAttribute('aria-label', `Ampliar ${nombre}`);
			tarjeta.dataset.originalSrc = ruta;
			miniatura.src = obtenerMiniatura(ruta);
			miniatura.dataset.originalSrc = ruta;
			miniatura.width = 400;
			miniatura.height = 533;
			miniatura.addEventListener('error', () => {
				if (miniatura.src !== new URL(ruta, document.baseURI).href) {
					miniatura.src = ruta;
				}
			}, { once: true });
			miniatura.alt = '';
			miniatura.loading = 'lazy';
			titulo.textContent = nombre;
			tarjeta.append(miniatura, titulo);
			galeriaActividad.append(tarjeta);
		});

		seccionActividad.append(encabezado, galeriaActividad);
		galeriaInfografias.append(seccionActividad);
	});
}

document.querySelectorAll('.unidad-block').forEach((unidad) => {
	unidad.addEventListener('toggle', () => {
		if (unidad.open) {
			document.querySelectorAll('.unidad-block[open]').forEach((otraUnidad) => {
				if (otraUnidad !== unidad) otraUnidad.open = false;
			});
		}
	});
});

selectoresSemanas.forEach((selectorSemanas) => {
	const unidadNumero = Number(selectorSemanas.closest('.unidad-block').dataset.unit);
	Object.keys(infografiasPorSemana).forEach((semana) => {
		const numeroSemana = Number(semana.match(/\d+/)[0]);
		const unidadSemana = numeroSemana <= 4 ? 1 : 2;
		if (unidadSemana !== unidadNumero) return;

		const boton = document.createElement('button');
		boton.className = 'week-button';
		boton.type = 'button';
		boton.id = `semana-${numeroSemana}`;
		boton.dataset.week = semana;
		boton.setAttribute('aria-pressed', 'false');
		boton.textContent = `Semana ${numeroSemana}`;
		selectorSemanas.append(boton);
	});
});

selectoresSemanas.forEach((selectorSemanas) => {
	selectorSemanas.addEventListener('click', (evento) => {
		const boton = evento.target.closest('[data-week]');
		if (!boton) return;

		selectorSemanas.querySelectorAll('[data-week]').forEach((semana) => {
			semana.setAttribute('aria-pressed', String(semana === boton));
		});
		const galeriaInfografias = selectorSemanas.closest('.unidad-body').querySelector('.infografia-grid');
		mostrarSemana(boton.dataset.week, galeriaInfografias);
	});
});

galeriasInfografias.forEach((galeriaInfografias) => {
	galeriaInfografias.addEventListener('click', (evento) => {
		const tarjeta = evento.target.closest('.infografia-card');
		if (!tarjeta) return;

		imagenesVisor = Array.from(galeriaInfografias.querySelectorAll('.infografia-card')).map((elemento) => ({
			src: elemento.dataset.originalSrc,
			titulo: elemento.querySelector('span').textContent,
			width: elemento.querySelector('img').naturalWidth || 400,
			height: elemento.querySelector('img').naturalHeight || 533
		}));
		abrirImagen(imagenesVisor.findIndex((imagen) => imagen.src === tarjeta.dataset.originalSrc));
		visorImagen.showModal();
	});
});

document.querySelector('.image-dialog-close').addEventListener('click', () => {
	visorImagen.close();
});

botonAnterior.addEventListener('click', () => abrirImagen(indiceImagenActual - 1));
botonSiguiente.addEventListener('click', () => abrirImagen(indiceImagenActual + 1));

document.addEventListener('keydown', (evento) => {
	if (!visorImagen.open) return;
	if (evento.key === 'Escape') {
		visorImagen.close();
	} else if (evento.key === 'ArrowLeft') {
		evento.preventDefault();
		abrirImagen(indiceImagenActual - 1);
	} else if (evento.key === 'ArrowRight') {
		evento.preventDefault();
		abrirImagen(indiceImagenActual + 1);
	}
});

function abrirSemanaDesdeHash() {
	const boton = document.getElementById(decodeURIComponent(location.hash.slice(1)));
	if (!boton || !boton.matches('[data-week]')) return;
	const unidad = boton.closest('.unidad-block');
	unidad.open = true;
	boton.click();
}

window.addEventListener('hashchange', abrirSemanaDesdeHash);
abrirSemanaDesdeHash();

visorImagen.addEventListener('click', (evento) => {
	if (evento.target === visorImagen) visorImagen.close();
});